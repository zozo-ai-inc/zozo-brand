"""Write every artifact to an output folder."""

from __future__ import annotations

import shutil
from pathlib import Path

from . import assets, config, sheet
from .wordmark import brand_wordmark

# Written into every folder this build creates. A folder is only ever emptied
# if it carries this file, so a mistyped --out cannot delete something else.
MARKER = ".zozo-brand-build"


def prepare(out: Path):
    if out.exists():
        if not out.is_dir():
            raise SystemExit(f"{out} exists and is not a folder")
        if any(out.iterdir()) and not (out / MARKER).exists():
            raise SystemExit(f"{out} is not empty and was not made by this build; choose another --out or empty it yourself")
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / MARKER).write_text("Generated by zozo_brand. This folder is emptied on every build.\n")


def build(out: Path, rasters=True, sheet_png=False, log=print) -> int:
    """Rebuild the output folder whole. Returns the number of files written."""
    for name in config.NAMES:
        for note in brand_wordmark(name).notes:
            log(f"note: {name}: {note}")

    # Draw everything before touching the folder, so a failure leaves the
    # previous build in place.
    files = {}
    for asset in assets.all_assets():
        files.update(asset.files(with_rasters=rasters))
    if rasters:
        files.update(assets.favicon_fallbacks())
    files.update(assets.color_files())
    page = sheet.html()
    files["brand-sheet.html"] = page.encode()

    prepare(out)
    for path, data in files.items():
        target = out / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    count = len(files)
    if sheet_png:
        sheet.screenshot(page, out / "brand-sheet.png")
        count += 1
    log(f"wrote {count} files to {out}")
    return count
